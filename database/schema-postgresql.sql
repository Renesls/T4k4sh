-- Didit procesa el documento y la prueba de vida. T4KASH conserva solamente
-- identificadores, estados y fechas; no duplica fotografias ni datos biometricos.
CREATE TABLE verificaciones_identidad (
    id_verificacion_identidad integer GENERATED BY DEFAULT AS IDENTITY,
    id_usuario integer NOT NULL,
    proveedor varchar(30) NOT NULL DEFAULT 'DIDIT',
    id_sesion_proveedor uuid NOT NULL,
    id_flujo_proveedor uuid,
    version_flujo integer,
    origen_solicitud varchar(30) NOT NULL DEFAULT 'PERFIL',
    estado_verificacion varchar(30) NOT NULL DEFAULT 'PENDIENTE',
    estado_proveedor varchar(40) NOT NULL DEFAULT 'Not Started',
    huella_documento varchar(64),
    motivo_resultado varchar(500),
    fecha_inicio timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_decision timestamp,
    fecha_expiracion timestamp,
    CONSTRAINT pk_verificaciones_identidad PRIMARY KEY (id_verificacion_identidad),
    CONSTRAINT uq_verificaciones_identidad_sesion UNIQUE (id_sesion_proveedor),
    CONSTRAINT ck_verificaciones_identidad_proveedor CHECK (
        proveedor ~ '^[A-Z][A-Z0-9_]{1,29}$'
    ),
    CONSTRAINT ck_verificaciones_identidad_origen CHECK (
        origen_solicitud IN ('PERFIL', 'WALLET', 'PAGO', 'TRABAJO', 'TAREA_RAPIDA', 'ADMIN')
    ),
    CONSTRAINT ck_verificaciones_identidad_estado CHECK (
        estado_verificacion IN (
            'PENDIENTE', 'EN_PROCESO', 'EN_REVISION', 'APROBADA', 'RECHAZADA',
            'EXPIRADA', 'VENCIDA', 'ABANDONADA', 'REQUIERE_ACCION', 'CANCELADA'
        )
    ),
    CONSTRAINT ck_verificaciones_identidad_version_flujo CHECK (
        version_flujo IS NULL OR version_flujo > 0
    ),
    CONSTRAINT ck_verificaciones_identidad_huella CHECK (
        huella_documento IS NULL OR huella_documento ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT ck_verificaciones_identidad_fechas CHECK (
        fecha_actualizacion >= fecha_inicio
        AND (fecha_decision IS NULL OR fecha_decision >= fecha_inicio)
        AND (fecha_expiracion IS NULL OR fecha_expiracion > fecha_inicio)
    ),
    CONSTRAINT ck_verificaciones_identidad_decision CHECK (
        estado_verificacion NOT IN ('APROBADA', 'RECHAZADA')
        OR fecha_decision IS NOT NULL
    )
);

