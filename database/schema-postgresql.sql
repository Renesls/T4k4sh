CREATE TABLE pagos (
    id_pago integer GENERATED BY DEFAULT AS IDENTITY,
    id_trabajo integer NOT NULL,
    id_cliente integer NOT NULL,
    id_estudiante integer NOT NULL,
    uuid_pago uuid NOT NULL DEFAULT gen_random_uuid(),
    proveedor_pago varchar(30) NOT NULL DEFAULT 'PAGADITO',
    entorno_pago varchar(20) NOT NULL DEFAULT 'SANDBOX',
    metodo_pago varchar(30) NOT NULL DEFAULT 'PAGADITO',
    moneda_cobro char(3) NOT NULL DEFAULT 'NIO',
    moneda_procesamiento char(3),
    tipo_cambio numeric(18,8),
    monto_procesamiento numeric(12,2),
    monto_estudiante numeric(12,2) NOT NULL,
    porcentaje_comision_plataforma numeric(5,2) NOT NULL DEFAULT 15.00,
    comision_plataforma numeric(12,2) NOT NULL DEFAULT 0,
    comision_cliente numeric(12,2) NOT NULL DEFAULT 0,
    comision_estudiante numeric(12,2) NOT NULL DEFAULT 0,
    comision_procesador numeric(12,2) NOT NULL DEFAULT 0,
    impuesto_procesador numeric(12,2) NOT NULL DEFAULT 0,
    monto_total_cliente numeric(12,2) NOT NULL,
    estado_pago varchar(40) NOT NULL DEFAULT 'PENDIENTE_PAGO',
    referencia_comercio varchar(100),
    referencia_proveedor varchar(150),
    fecha_creacion timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_expiracion timestamp,
    fecha_confirmacion timestamp,
    fecha_liberacion timestamp,
    fecha_reembolso timestamp,
    CONSTRAINT pk_pagos PRIMARY KEY (id_pago),
    CONSTRAINT uq_pagos_uuid UNIQUE (uuid_pago),
    CONSTRAINT uq_pagos_trabajo UNIQUE (id_trabajo),
    CONSTRAINT uq_pagos_referencia_comercio UNIQUE (referencia_comercio),
    CONSTRAINT ck_pagos_montos CHECK (
        monto_estudiante >= 0
        AND porcentaje_comision_plataforma BETWEEN 0 AND 100
        AND comision_plataforma >= 0
        AND comision_cliente >= 0
        AND comision_estudiante >= 0
        AND comision_plataforma = comision_cliente + comision_estudiante
        AND comision_procesador >= 0
        AND impuesto_procesador >= 0
        AND monto_total_cliente = monto_estudiante
            + comision_plataforma
            + comision_procesador
            + impuesto_procesador
        AND (monto_procesamiento IS NULL OR monto_procesamiento >= 0)
        AND (tipo_cambio IS NULL OR tipo_cambio > 0)
    ),
    CONSTRAINT ck_pagos_moneda_cobro CHECK (moneda_cobro ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_pagos_moneda_procesamiento CHECK (
        moneda_procesamiento IS NULL OR moneda_procesamiento ~ '^[A-Z]{3}$'
    ),
    CONSTRAINT ck_pagos_proveedor CHECK (proveedor_pago IN ('PAGADITO', 'EXTERNO')),
    CONSTRAINT ck_pagos_entorno CHECK (entorno_pago IN ('SANDBOX', 'PRODUCCION', 'EXTERNO')),
    CONSTRAINT ck_pagos_metodo CHECK (metodo_pago IN ('PAGADITO', 'EFECTIVO')),
    CONSTRAINT ck_pagos_efectivo CHECK (
        metodo_pago <> 'EFECTIVO'
        OR (
            proveedor_pago = 'EXTERNO'
            AND entorno_pago = 'EXTERNO'
            AND porcentaje_comision_plataforma = 0
            AND comision_plataforma = 0
            AND comision_procesador = 0
            AND impuesto_procesador = 0
            AND moneda_procesamiento IS NULL
            AND monto_procesamiento IS NULL
        )
    ),
    CONSTRAINT ck_pagos_pagadito CHECK (
        metodo_pago <> 'PAGADITO'
        OR (
            proveedor_pago = 'PAGADITO'
            AND entorno_pago IN ('SANDBOX', 'PRODUCCION')
        )
    )
);

